# Package/application IDs are dotted Java-style identifiers: >= 2
# segments, each starting with a letter or underscore, alphanumerics/
# underscores only after that -- what Gradle's own `applicationId`
# validation requires.
_PACKAGE_ID_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*(\.[A-Za-z_][A-Za-z0-9_]*)+$")

# Extensions this stage accepts for a raw icon/splash image -- kept
# narrow and explicit rather than accepting anything Android's
# res/drawable/ folder can technically hold, since a mismatched/exotic
# extension here would silently produce a resource file name Gradle's
# resource compiler rejects. See runtime.py's "v1" note on this being
# deliberately unrefined (no cropping/rasterization) for now.
_IMAGE_EXTENSIONS = {".png", ".jpg", ".jpeg", ".webp"}


class AndroidError(Exception):
    """Raised when a build directory can't be scaffolded into an Android project."""


@dataclass
class ScaffoldResult:
    project_dir: Path
    written_paths: list[Path] = field(default_factory=list)
    app_name: str = ""
    package_id: str = ""
    # Set when `project_dir` sits inside an *already existing* git repo
    # (i.e. some ancestor directory has a `.git`) rather than being a
    # repo root itself -- see `_find_enclosing_git_root`. GitHub Actions
    # only discovers `.github/workflows/` at a repo's root, so when this
    # is set the generated workflow needs to move there by hand.
    enclosing_git_root: Path | None = None
    # Whether a `--debug-keystore` was pinned into the project (copied
    # to `app/debug.keystore`) -- see `scaffold_project`'s docstring.
    # When False, the CLI warns: every machine (a fresh CI runner
    # included) will auto-generate its own debug key, so debug APKs
    # from different builds won't share a signature.
    has_debug_keystore: bool = False
    # Where each piece of identity came from, for the CLI to report --
    # see `_resolve_app_name`, `_resolve_package_id` and
    # `_resolve_system_bars`.
    app_name_source: str = ""
    package_id_source: str = ""
    # Opaque `#RRGGBB` driving the bars/window/splash, or None when the
    # Material theme colours are in use.
    system_bar_color: str | None = None
    system_bar_source: str = ""
    # Set when `status_bar_color = "auto"` found a value it couldn't use
    # and fell back to Material; says which value and why.
    system_bar_note: str | None = None
    # True when the package id was set in `arklight.config.py` (so the
    # CLI's "choose your own id" reminder is unnecessary).
    package_id_configured: bool = False


def _find_enclosing_git_root(project_dir: Path) -> Path | None:
    """
    Look for a `.git` in some *already existing* ancestor of
    `project_dir` -- not in `project_dir` itself, which won't exist yet
    at the point `scaffold_project` calls this, and which this function
    has no business creating a repo inside of anyway. Only intended to
    catch the "scaffolding into a subdirectory of a repo you already
    have checked out" case (e.g. `-o android/` inside a site's own
    working copy); doesn't distinguish that from `project_dir` simply
    being deeply nested under an unrelated repo (an unlikely enough
    layout that a false positive there just means an accurate, if
    slightly unnecessary, warning).
    """
    start = project_dir.resolve()
    # `start` may not exist yet (scaffold_project calls this before
    # creating anything); walk from the nearest existing ancestor.
    probe = start
    while not probe.exists():
        parent = probe.parent
        if parent == probe:
            return None
        probe = parent
    for ancestor in [probe, *probe.parents]:
        if (ancestor / ".git").exists():
            # `project_dir` itself already being a repo root is the
            # correct case (`.github/workflows/` belongs right there) --
            # only flag a strict *ancestor* of it.
            return ancestor if ancestor != start else None
    return None


def _validate_package_id(package_id: str) -> None:
    if not isinstance(package_id, str) or not _PACKAGE_ID_RE.match(package_id):
        raise AndroidError(
            f"Invalid android.package_id {package_id!r} -- must be a dotted "
            f"Java-style identifier with at least two segments (letters, "
            f"digits, underscores only; no segment may start with a digit), "
            f"e.g. 'com.example.myapp'."
        )


