"""
`arklight android scaffold` -- Stage 1 of
docs/Backends/ANDROID-BACKEND-IMPLEMENTATION.md.

    arklight android scaffold <build-dir> -o <project-dir>

Templating only, no toolchain required -- see that file's staged-order
table and docs/Foundational/DESIGN-NOTES.md's "v0.0438: Android
backend" section. This module is the CLI-facing counterpart to
`arklight.backend.android.runtime` (the pure template-content builder,
see its own docstring): it owns everything that module deliberately
leaves out -- reading `arklight.config.py`'s `"android"` section
(mirroring `arklight.cli.live_streaming`'s own `"live_streaming"`
read), resolving/validating that config against defaults, copying the
`build-dir` itself into `app/src/main/assets/`, copying in an optional
raw icon/splash image, and writing every generated file to disk. Same
"template builders never touch disk, the CLI module owns filesystem
writes" split `arklight.cli.scaffold` already established for
`arklight new`.

`arklight android scaffold`'s output also includes a ready-to-use
GitHub Actions workflow (`.github/workflows/android-build.yml`,
generated by `runtime.project_files` -- see
`runtime._github_ci_workflow_yml`) with two jobs: builds a debug APK
on GitHub-hosted runners on every push/PR (Stage 2) and installs and
launches it on a throwaway emulator on that same runner to confirm it
doesn't crash immediately on startup (Stage 3). Both are CI-only
build/install verification, no local toolchain required, folded into
this same command rather than a separate subcommand since they cost
nothing to generate. The release-build job (Stage 4) is opt-in --
`arklight android scaffold --release` -- since it's a no-op without a
keystore this tool has no business generating or holding; the flag
just wires the generated workflow to read one from repo secrets at
build time instead, see `runtime._github_ci_workflow_yml`. `arklight
android build` (Stage 5 -- shells out to a *local* `./gradlew
assembleDebug`, requires a JDK on this machine), `arklight android
build --install` (Stage 6 -- `adb install` onto a device/emulator the
user has actually connected), and `arklight android build --release`
(Stage 7 -- the same local shell-out targeting `assembleRelease`) are
separate, not-yet-implemented commands; this module only produces the
project shell, it never invokes Gradle or `adb` itself.

`.github/workflows/` is only discovered by GitHub Actions at a git
repository's *root*. This command has no reliable way to know whether
`output_dir` is meant to become its own repo (in which case writing
`.github/workflows/` there is correct) or is meant to be dropped in as
a subdirectory of an existing repo (in which case it isn't, and the
workflow silently never runs). Rather than guess -- or write files
outside the `output_dir` the caller explicitly asked for -- `scaffold_
project` walks upward from `output_dir` looking for an *already
existing* enclosing `.git` (one that isn't `output_dir` itself),
before generating any files. When found, `output_dir`'s path relative
to that enclosing root is threaded through to `runtime.project_files`
as `project_subdir`, so the generated workflow's Gradle steps already
carry the right `working-directory:` and artifact `path:` for that
layout -- it doesn't just build once moved, no manual editing needed.
The enclosing root itself is also surfaced on
`ScaffoldResult.enclosing_git_root` so the CLI layer
(`arklight.cli.main._cmd_android_scaffold`) can still tell the user
the workflow file needs to physically *move* there (the one thing
this function can't safely do for them, since `output_dir` is the
only place it's been told it may write).
"""

