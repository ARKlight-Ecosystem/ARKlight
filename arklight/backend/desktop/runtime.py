def _github_ci_workflow_yml(
    app_name: str,
    binary: str,
    *,
    project_subdir: str | None = None,
) -> str:
    """
    A GitHub Actions workflow, entirely on a GitHub-hosted Linux
    runner -- so a scaffolded project gets an automated build the
    moment it's generated, no local C toolchain or GTK3/WebKit2GTK
    dev headers required on the *user's own* machine. Mirrors
    `arklight.backend.android.runtime._github_ci_workflow_yml`'s single
    `assemble-debug` job: install the same apt packages this project's
    own README.md's "Building" section already tells a human to run,
    `make`, then upload `bin/<binary>` as a downloadable artifact.

    No install/launch smoke-test job (the Android workflow's Stage-3
    equivalent) here yet -- that's DESKTOP-BACKEND-IMPLEMENTATION.md's
    own Stage 3, tracked separately rather than folded into this
    function, since it needs a headless `Xvfb` display plus the
    WebKit2GTK runtime libs on the runner (distinct from the `-dev`
    headers this job already installs to *build*), not just this
    job's existing steps. This function only verifies the build
    compiles and links; Stage 3 will add the "does it also launch
    without crashing" check on top of what it produces.

    `project_subdir`, if given, is the project's path relative to the
    repo root the workflow will actually run from -- e.g. `"desktop"`
    when `arklight desktop scaffold` wrote this project into an
    existing repo's `desktop/` subdirectory rather than at that repo's
    own root (see `arklight.cli.desktop._find_enclosing_git_root`,
    itself mirroring `arklight.cli.android._find_enclosing_git_root`).
    When set, the `make` step gets a matching `working-directory:`,
    and the uploaded binary's path is prefixed with it -- otherwise
    `make` looks for a `Makefile` in the checkout root and fails
    immediately, since checkout always happens at the *repo* root, not
    wherever this project was scaffolded into. `None` (the default)
    means this project IS the repo root, matching the original
    no-subdirectory behavior.
    """
    # Used only in the uploaded artifact's display name -- purely
    # cosmetic, so it's slugified defensively rather than validated
    # the way `app_id`/`app_name` are elsewhere in this module. Same
    # reasoning as the Android workflow generator's own `slug`.
    slug = re.sub(r"[^A-Za-z0-9._-]+", "-", app_name).strip("-") or "arklight-app"
    working_directory_line = f"\n        working-directory: {project_subdir}" if project_subdir else ""
    path_prefix = f"{project_subdir}/" if project_subdir else ""
    return f'''\
name: Desktop build

# Builds the native GTK3 + WebKit2GTK host on a GitHub-hosted Linux
# runner on every push/PR, so a build regression is caught without any
# of the dev headers below needing to exist on a contributor's own
# machine. No install/launch smoke test yet -- see
# DESKTOP-BACKEND-IMPLEMENTATION.md's Stage 3.
on:
  push:
    branches: [main]
  pull_request:
  workflow_dispatch:

jobs:
  build:
    name: Build (Linux)
    runs-on: ubuntu-latest
    steps:
      - name: Check out the project
        uses: actions/checkout@v4

      - name: Install GTK3 + WebKit2GTK dev headers
        run: |
          sudo apt-get update
          sudo apt-get install -y build-essential pkg-config libgtk-3-dev libwebkit2gtk-4.1-dev

      - name: Build{working_directory_line}
        run: make

      - name: Upload binary
        uses: actions/upload-artifact@v4
        with:
          name: {slug}-linux
          path: {path_prefix}bin/{binary}
          if-no-files-found: error
'''


def _desktop_entry(app_name: str, app_id: str, binary: str) -> str:
    # Freedesktop Desktop Entry format -- see
    # https://specifications.freedesktop.org/desktop-entry-spec/latest/.
    # `Exec` deliberately has no path prefix: README.md tells the user
    # to either run this from the project's own `bin/` directory or
    # edit `Exec` to an absolute path once they've installed the
    # binary somewhere on PATH -- this scaffold has no reliable way to
    # know that final install location up front. No `Icon=` key for
    # now -- icon support isn't implemented yet, see README.md.
    return f"""\
[Desktop Entry]
Type=Application
Name={app_name}
Exec={binary}
Terminal=false
Categories=Utility;
StartupWMClass={app_id}
"""


def _readme_md(app_name: str, app_id: str, binary: str) -> str:
    return f"""\
# {app_name} (desktop)

Generated by `arklight desktop scaffold` -- a small native GTK3 +
WebKit2GTK host that loads the packaged ARKlight site in
`assets.gen.c` from memory, through an in-process `ark:` resource
scheme. **Linux only for now** -- see
docs/Backends/DESKTOP-BACKEND-IMPLEMENTATION.md in the ARKlight
repository for the staged plan covering other platforms and a real
local `arklight desktop build` command.

## Building

Needs a C compiler, `pkg-config`, and the GTK3 + WebKit2GTK
development headers.

Debian / Ubuntu:

```sh
sudo apt install build-essential pkg-config libgtk-3-dev libwebkit2gtk-4.1-dev
```

Fedora:

```sh
sudo dnf install gcc pkgconf-pkg-config gtk3-devel webkit2gtk4.1-devel
```

Arch Linux:

```sh
sudo pacman -S base-devel pkgconf gtk3 webkit2gtk-4.1
```

Then, from this directory:

```sh
make
./bin/{binary}
```

(or `make run`, which does both).

## What's in here

| File | What it is |
| --- | --- |
| `main.c` | The native host -- window, WebView, `ark:` scheme handler, external-link policy. Hand-editable, but re-running `arklight desktop scaffold` will overwrite it. |
| `assets.gen.c` / `assets.gen.h` | The packaged site (every file from the `arklight build` output directory this was scaffolded from), embedded as C byte arrays. Regenerated fresh on every `arklight desktop scaffold` run -- don't hand-edit. |
| `Makefile` | Builds `bin/{binary}` from the two files above. |
| `{app_id}.desktop` | A [freedesktop Desktop Entry](https://specifications.freedesktop.org/desktop-entry-spec/latest/) launcher. Edit `Exec=` to an absolute path (or put `bin/{binary}` on your `PATH`) and copy it to `~/.local/share/applications/` to add a launcher-menu entry. |
| `.github/workflows/desktop-build.yml` | A GitHub Actions workflow that builds this project on a GitHub-hosted Linux runner on every push/PR and uploads `bin/{binary}` as a downloadable artifact -- no local toolchain needed for that. Regenerated fresh on every `arklight desktop scaffold` run; it's a normal, hand-editable workflow file, not something only this tool may touch. **Note:** this workflow only fires on GitHub if `.github/workflows/` sits at your repository's *root* -- if `arklight desktop scaffold` told you this project is nested inside an existing repo, move this file there first (see that command's own terminal output for the exact paths). |

## Updating the packaged site

Re-run `arklight build`, then `arklight desktop scaffold` again on the
same output directory (into this same project directory) to refresh
`assets.gen.c`/`assets.gen.h` with the new content, then `make` again.

## Not implemented yet

Per docs/Backends/DESKTOP-BACKEND-IMPLEMENTATION.md's staged plan:
app/window icons, a sealed `.ark` bundle as the embedded payload
(this scaffold embeds the unpacked build directory instead -- see
`arklight.backend.desktop.runtime`'s module docstring for why),
a local `arklight desktop build` command that runs this `Makefile` for
you, and Windows/macOS targets. A GitHub Actions CI build is already
included -- see `.github/workflows/desktop-build.yml` above.
"""


# ---------------------------------------------------------------------------
# Embedded asset store (assets.gen.c / assets.gen.h)
# ---------------------------------------------------------------------------

# Bytes per line in a generated byte-array literal -- purely
# cosmetic (keeps `assets.gen.c` from being one line per file), has no
# effect on the compiled output.
_BYTES_PER_LINE = 16


def _c_byte_array_body(data: bytes) -> str:
    lines = []
    for i in range(0, len(data), _BYTES_PER_LINE):
        chunk = data[i : i + _BYTES_PER_LINE]
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in chunk) + ",")
    return "\n".join(lines)


def generate_assets_source(files: dict[str, bytes]) -> tuple[str, str]:
    """
    Build `(assets.gen.c contents, assets.gen.h contents)` embedding
    every `{build-relative posix path: bytes}` entry in `files` as a C
    byte array, indexed by path in a generated `ark_assets[]` table --
    see the module docstring's "embedded asset store" section for why
    this embeds the unpacked tree rather than a `.ark` bundle.

    `files` is expected already sorted/deterministic-ordered by the
    caller (`arklight.cli.desktop.scaffold_project` walks the build
    directory with `sorted(...)`) -- this function doesn't re-sort, so
    a caller that hands in an unsorted dict gets a non-deterministic
    `assets.gen.c` between runs, which is their bug to avoid, not this
    function's to silently paper over.
    """
    import mimetypes

    header_lines = [
        "/* Generated by `arklight desktop scaffold` -- do not edit by hand,",
        " * re-run the scaffold command instead. See assets.gen.c. */",
        "#pragma once",
        "",
        "#include <stddef.h>",
        "",
        "typedef struct {",
        "    const char *path;   /* build-relative, no leading slash, e.g. \"assets/logo.svg\" */",
        "    const char *mime;",
        "    const unsigned char *data;",
        "    size_t len;",
        "} ArkAsset;",
        "",
        "extern const ArkAsset ark_assets[];",
        "extern const size_t ark_asset_count;",
        "",
    ]
    header = "\n".join(header_lines)

    source_lines = [
        "/* Generated by `arklight desktop scaffold` -- do not edit by hand,",
        " * re-run the scaffold command instead. */",
        '#include "assets.gen.h"',
        "",
    ]

    table_lines = []
    for index, (path, data) in enumerate(files.items()):
        mime, _ = mimetypes.guess_type(path)
        if mime is None:
            mime = "application/octet-stream"
        var = f"ark_asset_{index}"
        source_lines.append(f"static const unsigned char {var}[] = {{")
        if data:
            source_lines.append(_c_byte_array_body(data))
        source_lines.append("};")
        source_lines.append("")
        escaped_path = _c_string_literal(path)
        escaped_mime = _c_string_literal(mime)
        table_lines.append(f"    {{ {escaped_path}, {escaped_mime}, {var}, sizeof({var}) }},")

    source_lines.append("const ArkAsset ark_assets[] = {")
    source_lines.extend(table_lines)
    source_lines.append("};")
    source_lines.append("")
    source_lines.append(
        f"const size_t ark_asset_count = {len(files)};"
    )
    source_lines.append("")

    return "\n".join(source_lines), header
