"""
Template content for `arklight desktop scaffold` -- Linux-only target
for now, per docs/Backends/DESKTOP-BACKEND-IMPLEMENTATION.md and the
architecture in docs/Backends/ARKLIGHT_DESKTOP_BACKEND_PROPOSAL.md.

Every function here is a pure `(...) -> str` (or `-> tuple[str, str]`)
builder -- no disk I/O, same "template builders never touch disk, the
CLI module owns filesystem writes" split `arklight.backend.android.
runtime` already established for the Android backend. Only
`arklight.cli.desktop` (the CLI-facing module) reads a build
directory's bytes and writes anything to disk.

Two things get generated:

- **The native host itself** (`main.c`, `Makefile`, `.gitignore`, a
  freedesktop `.desktop` launcher entry, a GitHub Actions workflow at
  `.github/workflows/desktop-build.yml` (see `_github_ci_workflow_yml`
  -- mirrors the Android backend's own generated workflow, see
  `arklight.backend.android.runtime`'s module docstring), `README.md`)
  -- a small GTK3 + WebKit2GTK program, per the proposal's "native
  host responsibilities" (section 4): create the window, initialize
  the platform WebView, register an in-process `ark:` resource scheme
  backed by an in-memory asset store, load the entry document, and
  enforce a navigation policy that opens anything outside that scheme
  in the user's default external handler instead of navigating the
  app window away from the packaged site.
- **The embedded asset store** (`assets.gen.c`/`assets.gen.h`,
  generated by `generate_assets_source`) -- every file from an
  `arklight build` output directory, embedded as C byte arrays and
  indexed by its build-relative path. This is the "unpacked tree"
  choice the Android backend's Stage 1 also picked as its default
  (see ANDROID-BACKEND-IMPLEMENTATION.md's "Open questions for
  Stage 0"): simpler than parsing a `.ark` bundle's zip/sealing format
  from C, and it keeps the native host free of a zip/crypto
  dependency for this first target. Packing as a real sealed `.ark`
  bundle (matching the proposal's section 5) is future work, tracked
  in DESKTOP-BACKEND-IMPLEMENTATION.md rather than pinned down here.

Byte arrays are plain C literals (`{0x3c, 0x21, ...}`), not a linker
trick (`ld -r -b binary`, `objcopy`, `#embed`) -- portable across
whatever C toolchain the user's distro ships, at the cost of a
noticeably large generated `assets.gen.c` for a large site. Acceptable
for a first Linux-only target; revisit if that ever becomes the
bottleneck a real site hits.
"""

from __future__ import annotations

import re

# GTK/WebKit soname suite this scaffold's Makefile probes for, newest
# first -- see `_makefile`. `webkit2gtk-4.1` is what current
# Debian/Ubuntu/Fedora ship; `webkit2gtk-4.0` is kept as a fallback
# for older distros still on it. Both expose the same API surface
# `main.c` uses here.
_WEBKIT_PKG_CANDIDATES = ("webkit2gtk-4.1", "webkit2gtk-4.0")

# Characters allowed in a generated Makefile/.desktop binary name --
# kept conservative (lowercase letters, digits, hyphens) so the result
# is safe to use unquoted as a Makefile target and a Desktop Entry
# `Exec=` value, regardless of what `app_name` contains.
_BINARY_NAME_DISALLOWED_RE = re.compile(r"[^a-z0-9-]+")


def binary_name(app_name: str) -> str:
    """
    Derive a safe, lowercase, hyphenated binary/target name from
    `app_name` (e.g. `"My Cool Site!"` -> `"my-cool-site"`). Falls
    back to `"arklight-app"` if nothing alphanumeric survives (e.g.
    an app name that's entirely emoji/punctuation) rather than
    producing an empty Makefile target name.
    """
    slug = _BINARY_NAME_DISALLOWED_RE.sub("-", app_name.strip().lower()).strip("-")
    return slug or "arklight-app"


def _c_string_literal(value: str) -> str:
    """Escape `value` for use inside a C string literal (backslashes,
    double quotes, and newlines -- the only characters `main.c`'s
    `#define ARK_*` macros could plausibly receive from an
    `arklight.config.py` author's `app_name`/`window_title`)."""
    escaped = value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    return f'"{escaped}"'


def project_files(
    *,
    app_name: str,
    app_id: str,
    window_title: str,
    width: int,
    height: int,
    resizable: bool,
    project_subdir: str | None = None,
) -> dict[str, str]:
    """
    Return `{relative_path: contents}` for every *generated text* file
    in the Linux desktop host project -- everything except the
    embedded asset store (`assets.gen.c`/`assets.gen.h`, built
    separately by `generate_assets_source` since it needs the actual
    build directory's bytes, not just app identity).

    `app_id` is a reverse-DNS identifier (same shape as the Android
    backend's `package_id`) used as the `.desktop` launcher's filename
    and the window's program name (`g_set_prgname`, which GTK uses to
    derive `WM_CLASS`) -- not a Python/Java package, just a stable,
    namespaced identifier for this one app.

    `project_subdir` is forwarded as-is to `_github_ci_workflow_yml`
    -- see that function's own docstring, and `arklight.backend.
    android.runtime.project_files`'s identical parameter, which this
    mirrors.
    """
    name = binary_name(app_name)
    return {
        "main.c": _main_c(app_name, app_id, window_title, width, height, resizable),
        "Makefile": _makefile(name),
        ".gitignore": _GITIGNORE,
        f"{app_id}.desktop": _desktop_entry(app_name, app_id, name),
        ".github/workflows/desktop-build.yml": _github_ci_workflow_yml(
            app_name, name, project_subdir=project_subdir
        ),
        "README.md": _readme_md(app_name, app_id, name),
    }


# ---------------------------------------------------------------------------
# main.c
# ---------------------------------------------------------------------------


def _main_c(
    app_name: str, app_id: str, window_title: str, width: int, height: int, resizable: bool
) -> str:
    return f'''\
/*
 * ARKlight desktop host -- Linux (GTK3 + WebKit2GTK).
 *
 * Generated by `arklight desktop scaffold`; see
 * docs/Backends/DESKTOP-BACKEND-IMPLEMENTATION.md and
 * docs/Backends/ARKLIGHT_DESKTOP_BACKEND_PROPOSAL.md (section 4,
 * "Native host responsibilities") for the design this implements.
 *
 * This is a launcher and resource provider for the packaged ARKlight
 * site in assets.gen.c, not a second application framework: it
 * creates one window, registers an in-process "ark:" resource scheme
 * backed by that embedded asset table, points a WebKitWebView at it,
 * and sends any navigation outside that scheme to the user's default
 * external handler instead of following it in this window. No custom
 * native JavaScript API is exposed to the page (proposal section 10).
 */

#include <gtk/gtk.h>
#include <webkit2/webkit2.h>
#include <string.h>

#include "assets.gen.h"

#define ARK_APP_NAME {_c_string_literal(app_name)}
#define ARK_APP_ID {_c_string_literal(app_id)}
#define ARK_WINDOW_TITLE {_c_string_literal(window_title)}
#define ARK_WINDOW_WIDTH {int(width)}
#define ARK_WINDOW_HEIGHT {int(height)}
#define ARK_RESIZABLE {"TRUE" if resizable else "FALSE"}

/* Look up `path` (as handed to us by WebKitURISchemeRequest, e.g.
 * "/about.html", or "/" for the bare root) in the embedded asset
 * table. Returns NULL if there's no such asset, or if `path` contains
 * a "..segment -- an embedded, read-only asset table never
 * legitimately needs to escape itself, so that's rejected outright
 * rather than resolved (see the proposal's "path traversal is
 * rejected" bundle-test requirement). */
static const ArkAsset *ark_find_asset(const char *path) {{
    if (path == NULL || path[0] == '\\0' || strcmp(path, "/") == 0) {{
        path = "/index.html";
    }}
    if (path[0] == '/') {{
        path++;
    }}
    if (strstr(path, "..") != NULL) {{
        return NULL;
    }}
    for (size_t i = 0; i < ark_asset_count; i++) {{
        if (strcmp(ark_assets[i].path, path) == 0) {{
            return &ark_assets[i];
        }}
    }}
    return NULL;
}}

static void ark_handle_scheme_request(WebKitURISchemeRequest *request, gpointer user_data) {{
    (void) user_data;
    const char *path = webkit_uri_scheme_request_get_path(request);
    const ArkAsset *asset = ark_find_asset(path);

    if (asset == NULL) {{
        GError *error = g_error_new(
            WEBKIT_NETWORK_ERROR, WEBKIT_NETWORK_ERROR_FAILED,
            "ARKlight: resource not found: %s", path ? path : "(null)");
        webkit_uri_scheme_request_finish_error(request, error);
        g_error_free(error);
        return;
    }}

    GInputStream *stream =
        g_memory_input_stream_new_from_data(asset->data, (gssize) asset->len, NULL);
    webkit_uri_scheme_request_finish(request, stream, (gint64) asset->len, asset->mime);
    g_object_unref(stream);
}}

/* Routing/navigation policy (proposal section 9): "ark:" requests are
 * this app's own packaged resources and load normally; everything
 * else (https://, http://, mailto:, ...) is handed to the platform's
 * default external handler instead of navigating this window there --
 * an embedded desktop shell has no business becoming a general-
 * purpose web browser. */
static gboolean ark_decide_policy(WebKitWebView *view, WebKitPolicyDecision *decision,
                                   WebKitPolicyDecisionType type, gpointer user_data) {{
    (void) view;
    (void) user_data;
    if (type != WEBKIT_POLICY_DECISION_TYPE_NAVIGATION_ACTION &&
        type != WEBKIT_POLICY_DECISION_TYPE_NEW_WINDOW_ACTION) {{
        return FALSE;
    }}

    WebKitNavigationPolicyDecision *nav = WEBKIT_NAVIGATION_POLICY_DECISION(decision);
    WebKitNavigationAction *action = webkit_navigation_policy_decision_get_navigation_action(nav);
    WebKitURIRequest *req = webkit_navigation_action_get_request(action);
    const char *uri = webkit_uri_request_get_uri(req);

    if (uri != NULL && g_str_has_prefix(uri, "ark:")) {{
        return FALSE; /* let the WebView load it via our scheme handler */
    }}

    webkit_policy_decision_ignore(decision);
    if (uri != NULL) {{
        GError *error = NULL;
        if (!g_app_info_launch_default_for_uri(uri, NULL, &error)) {{
            g_warning("ARKlight: could not open external link %s: %s", uri,
                      error ? error->message : "unknown error");
            if (error != NULL) {{
                g_error_free(error);
            }}
        }}
    }}
    return TRUE;
}}

int main(int argc, char *argv[]) {{
    /* Sets the program name GTK derives WM_CLASS from -- must happen
     * before gtk_init(). */
    g_set_prgname(ARK_APP_ID);
    gtk_init(&argc, &argv);

    WebKitWebContext *context = webkit_web_context_get_default();
    webkit_web_context_register_uri_scheme(context, "ark", ark_handle_scheme_request, NULL, NULL);

    GtkWidget *window = gtk_window_new(GTK_WINDOW_TOPLEVEL);
    gtk_window_set_title(GTK_WINDOW(window), ARK_WINDOW_TITLE);
    gtk_window_set_default_size(GTK_WINDOW(window), ARK_WINDOW_WIDTH, ARK_WINDOW_HEIGHT);
    gtk_window_set_resizable(GTK_WINDOW(window), ARK_RESIZABLE);
    g_signal_connect(window, "destroy", G_CALLBACK(gtk_main_quit), NULL);

    WebKitWebView *view = WEBKIT_WEB_VIEW(webkit_web_view_new());
    g_signal_connect(view, "decide-policy", G_CALLBACK(ark_decide_policy), NULL);
    gtk_container_add(GTK_CONTAINER(window), GTK_WIDGET(view));

    webkit_web_view_load_uri(view, "ark:///index.html");

    gtk_widget_show_all(window);
    gtk_main();
    return 0;
}}
'''


