def _makefile(binary: str) -> str:
    # Probes for webkit2gtk-4.1 first, falls back to -4.0 -- see
    # `_WEBKIT_PKG_CANDIDATES`. A `for`/`break` loop, not a chained
    # `A && echo X || B && echo Y` one-liner: `&&`/`||` share the same
    # precedence and left-associate, so `(A && echo X) || B` is one
    # group that `&& echo Y` then runs unconditionally against --
    # printing *both* candidates whenever the first one matches. The
    # loop has no such trap. `?=` on PKG_CONFIG (not `=`) lets a
    # caller override it (e.g. `PKG_CONFIG=pkgconf make`) the same way
    # `CC`/`CFLAGS` are already overridable via `make`'s own built-in
    # rules.
    candidates = " ".join(_WEBKIT_PKG_CANDIDATES)
    probe = (
        f"for p in {candidates}; do "
        f"$(PKG_CONFIG) --exists $$p 2>/dev/null && {{ echo $$p; break; }}; "
        f"done"
    )
    return f'''\
# Generated by `arklight desktop scaffold` -- Linux only for now (GTK3
# + WebKit2GTK). See README.md for the system packages this needs.

PKG_CONFIG ?= pkg-config
WEBKIT_PKG := $(shell {probe})

CFLAGS  += -std=c11 -Wall -Wextra $(shell $(PKG_CONFIG) --cflags gtk+-3.0 $(WEBKIT_PKG))
LDLIBS  += $(shell $(PKG_CONFIG) --libs gtk+-3.0 $(WEBKIT_PKG))

SRC := main.c assets.gen.c
OBJ := $(SRC:.c=.o)
BIN := bin/{binary}

.PHONY: all clean run

all: $(BIN)

$(BIN): $(OBJ)
	@mkdir -p bin
	$(CC) $(OBJ) -o $@ $(LDLIBS)

%.o: %.c assets.gen.h
	$(CC) $(CFLAGS) -c $< -o $@

run: $(BIN)
	./$(BIN)

clean:
	rm -f $(OBJ)
	rm -rf bin
'''


_GITIGNORE = """\
# Build output
*.o
/bin/
"""


